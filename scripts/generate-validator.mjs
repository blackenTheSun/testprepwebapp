// Compiles each test-file JSON Schema version into a standalone validator module at build time,
// so the delivered page never compiles schemas (or evaluates generated code) at runtime.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'src/contract/generated');
const VERSIONS = ['v1', 'v2'];

const DECLARATION = `// Generated by scripts/generate-validator.mjs. Do not edit.
export interface SchemaError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  params: Record<string, unknown>;
  message?: string;
}
declare const validate: ((data: unknown) => boolean) & { errors?: SchemaError[] | null };
export default validate;
`;

mkdirSync(outDir, { recursive: true });
for (const version of VERSIONS) {
  const schemaPath = resolve(root, `src/contract/test-file.local.${version}.schema.json`);
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);
  const source = standaloneCode.default ? standaloneCode.default(ajv, validate) : standaloneCode(ajv, validate);

  // Ajv's ESM output still emits CommonJS require() for runtime helpers; hoist them to imports.
  const imports = [];
  const esmSource = source.replace(/const (\w+) = require\("([^"]+)"\)\.default;/g, (_m, name, mod) => {
    imports.push(`import ${name}Module from '${mod}.js';\nconst ${name} = ${name}Module.default ?? ${name}Module;`);
    return '';
  });
  if (/require\(/.test(esmSource)) throw new Error(`Unhandled require() in generated ${version} validator`);

  const name = `schemaValidator${version.toUpperCase()}`;
  writeFileSync(
    resolve(outDir, `${name}.js`),
    `// @ts-nocheck\n// Generated by scripts/generate-validator.mjs. Do not edit.\n${imports.join('\n')}\n${esmSource}`,
  );
  writeFileSync(resolve(outDir, `${name}.d.ts`), DECLARATION);
  console.log(`Generated src/contract/generated/${name}.js`);
}
